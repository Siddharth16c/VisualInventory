-- ─── Layer 1: Storage Places (Buildings/Stores) ──────────────

CREATE TABLE IF NOT EXISTS storage_places (
  id bigserial PRIMARY KEY,
  firm_id uuid NOT NULL REFERENCES firms(id) ON DELETE CASCADE,
  place_name text NOT NULL,            -- "KT Shop", "Godown B"
  place_slug text NOT NULL,            -- "KT", "GDB" — short label for auto-labels
  place_type text NOT NULL DEFAULT 'shop',  -- 'shop' | 'warehouse' | 'godown'
  floor_count int NOT NULL DEFAULT 1,
  top_view_image_url text,             -- optional photo/sketch of the building
  notes text,
  deleted_at timestamptz,              -- soft delete (NULL = active)
  created_at timestamptz DEFAULT now(),
  UNIQUE(firm_id, place_slug)
);

-- ─── Layer 2: Zones (Named regions within a floor) ───────────
-- polygon_coords stores [[x,y], [x,y], ...] for Three.js rendering.

CREATE TABLE IF NOT EXISTS storage_zones (
  id bigserial PRIMARY KEY,
  firm_id uuid NOT NULL REFERENCES firms(id) ON DELETE CASCADE,
  place_id bigint NOT NULL REFERENCES storage_places(id) ON DELETE RESTRICT,
  floor_num int NOT NULL DEFAULT 0,         -- 0 = ground floor
  zone_name text NOT NULL,                  -- "Back Staircase Corner"
  zone_slug text NOT NULL,                  -- "BSC"
  zone_label text,                          -- auto-generated by trigger: "KT-F0-BSC"
  polygon_coords jsonb,                     -- [[x,y],[x,y],...] for Three.js
  zone_color text DEFAULT '#4f46e5',        -- hex color for 3D highlight
  notes text,
  deleted_at timestamptz,                   -- soft delete
  UNIQUE(place_id, floor_num, zone_slug)
);

-- ─── Layer 3: Slots (Named spots within a zone) ─────────────

CREATE TABLE IF NOT EXISTS storage_slots (
  id bigserial PRIMARY KEY,
  firm_id uuid NOT NULL REFERENCES firms(id) ON DELETE CASCADE,
  zone_id bigint NOT NULL REFERENCES storage_zones(id) ON DELETE RESTRICT,
  slot_name text NOT NULL,                  -- "Stack A"
  slot_label text,                          -- auto-generated by trigger: "KT-F0-BSC-STACK_A"
  order_index int DEFAULT 0,               -- z-level: 0 = floor, 1 = on top, 2 = above that
  capacity_parcels int,                     -- NULL = unknown/chaotic
  notes text,
  deleted_at timestamptz                    -- soft delete
);

-- ─── Stock ↔ Slot Assignment ─────────────────────────────────

CREATE TABLE IF NOT EXISTS item_locations (
  id bigserial PRIMARY KEY,
  firm_id uuid NOT NULL REFERENCES firms(id) ON DELETE CASCADE,
  item_id bigint NOT NULL REFERENCES items(id) ON DELETE CASCADE,
  slot_id bigint NOT NULL REFERENCES storage_slots(id) ON DELETE RESTRICT,
  parcel_count int NOT NULL DEFAULT 0,
  is_primary boolean DEFAULT false,
  packaging_type text,                      -- "gunny bag", "brown box medium", "carry bag"
  packaging_tags text[] DEFAULT '{}',       -- {"fragile", "seasonal", "holi"}
  last_verified_at timestamptz,
  updated_at timestamptz DEFAULT now(),
  deleted_at timestamptz,                   -- soft delete
  UNIQUE(item_id, slot_id)
);

-- ═══════════════════════════════════════════════════════════════
-- AUTO-LABEL TRIGGERS
-- Ensures zone_label and slot_label stay accurate even on rename.
-- ═══════════════════════════════════════════════════════════════

-- Trigger: auto-generate zone_label = "PLACE_SLUG-F{floor}-ZONE_SLUG"
CREATE OR REPLACE FUNCTION generate_zone_label()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE
  p_slug text;
BEGIN
  SELECT place_slug INTO p_slug
  FROM storage_places WHERE id = NEW.place_id;

  NEW.zone_label := p_slug || '-F' || NEW.floor_num || '-' || NEW.zone_slug;
  RETURN NEW;
END;
$$;

CREATE TRIGGER trg_zone_label
  BEFORE INSERT OR UPDATE OF zone_slug, floor_num, place_id
  ON storage_zones
  FOR EACH ROW
  EXECUTE FUNCTION generate_zone_label();

-- Trigger: auto-generate slot_label = "ZONE_LABEL-SLOT_NAME_UPPER"
CREATE OR REPLACE FUNCTION generate_slot_label()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE
  z_label text;
BEGIN
  SELECT zone_label INTO z_label
  FROM storage_zones WHERE id = NEW.zone_id;

  NEW.slot_label := z_label || '-' || UPPER(REPLACE(NEW.slot_name, ' ', '_'));
  RETURN NEW;
END;
$$;

CREATE TRIGGER trg_slot_label
  BEFORE INSERT OR UPDATE OF slot_name, zone_id
  ON storage_slots
  FOR EACH ROW
  EXECUTE FUNCTION generate_slot_label();

-- Cascade label updates: when a zone_slug or place_slug changes,
-- re-fire slot labels by touching all child slots.
CREATE OR REPLACE FUNCTION cascade_zone_label_to_slots()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
  IF OLD.zone_label IS DISTINCT FROM NEW.zone_label THEN
    UPDATE storage_slots
    SET slot_name = slot_name  -- no-op update triggers trg_slot_label
    WHERE zone_id = NEW.id AND deleted_at IS NULL;
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER trg_cascade_zone_to_slots
  AFTER UPDATE OF zone_label
  ON storage_zones
  FOR EACH ROW
  EXECUTE FUNCTION cascade_zone_label_to_slots();

