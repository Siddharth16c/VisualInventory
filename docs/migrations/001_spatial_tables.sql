-- PERFORMANCE INDEXES
-- ═══════════════════════════════════════════════════════════════

CREATE INDEX IF NOT EXISTS idx_storage_zones_place
  ON storage_zones(place_id, floor_num) WHERE deleted_at IS NULL;

CREATE INDEX IF NOT EXISTS idx_storage_slots_zone
  ON storage_slots(zone_id) WHERE deleted_at IS NULL;

CREATE INDEX IF NOT EXISTS idx_item_locations_item
  ON item_locations(item_id) WHERE deleted_at IS NULL;

CREATE INDEX IF NOT EXISTS idx_item_locations_slot
  ON item_locations(slot_id) WHERE deleted_at IS NULL;

CREATE INDEX IF NOT EXISTS idx_storage_slots_order
  ON storage_slots(zone_id, order_index) WHERE deleted_at IS NULL;

-- ═══════════════════════════════════════════════════════════════
-- HELPER VIEW: Item → Full Location Path
-- Excludes soft-deleted records. For search: "WHERE is item X?"
-- ═══════════════════════════════════════════════════════════════

CREATE OR REPLACE VIEW item_location_full AS
SELECT
  il.id,
  il.firm_id,
  il.item_id,
  i.item_name,
  il.slot_id,
  ss.slot_name,
  ss.slot_label,
  ss.order_index,
  il.parcel_count,
  il.is_primary,
  il.packaging_type,
  il.packaging_tags,
  sz.id AS zone_id,
  sz.zone_name,
  sz.zone_label,
  sz.floor_num,
  sz.polygon_coords,
  sz.zone_color,
  sp.id AS place_id,
  sp.place_name,
  sp.place_slug,
  sp.place_type
FROM item_locations il
JOIN storage_slots ss ON ss.id = il.slot_id     AND ss.deleted_at IS NULL
JOIN storage_zones sz ON sz.id = ss.zone_id     AND sz.deleted_at IS NULL
JOIN storage_places sp ON sp.id = sz.place_id   AND sp.deleted_at IS NULL
JOIN items i ON i.id = il.item_id
WHERE il.deleted_at IS NULL;
